"""Write the README methods table from a successful seed-0 pytest artifact."""

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = "<!-- methods-vs-truth:start -->"
END = "<!-- methods-vs-truth:end -->"
METHODS = (
    "Randomised A/B: repeat",
    "Naive before/after: completion",
    "Naive before/after: drawdown",
    "TWFE DiD: completion",
    "TWFE DiD: drawdown",
    "Hierarchical: mean baseline",
)


def render(evidence: dict) -> str:
    rows = evidence["rows"]
    if evidence["exitstatus"] != 0 or evidence["seed"] != 0 or evidence["tests_collected"] <= 0:
        raise ValueError("Need a successful seed-0 pytest run")
    if len(rows) != len(METHODS) or {row["method"] for row in rows} != set(METHODS):
        raise ValueError("Need exactly one passing result for every reported estimator")
    by_method = {row["method"]: row for row in rows}
    lines = [
        "| Method | Estimate | 95% interval | Truth | Bias |",
        "|---|---:|---:|---:|---:|",
    ]
    for method in METHODS:
        row = by_method[method]
        estimate, truth, bias = (row[key] for key in ("estimate", "truth", "bias"))
        lo, hi = row["ci95"]
        if not all(math.isfinite(v) for v in (estimate, truth, bias, lo, hi)) or lo > hi:
            raise ValueError("Invalid estimate or interval")
        if not math.isclose(bias, estimate - truth, abs_tol=1e-10):
            raise ValueError("Bias must equal estimate minus truth")
        lines.append(f"| {method} | {estimate:.2f} | [{lo:.2f}, {hi:.2f}] | {truth:.2f} | {bias:+.2f} |")
    metadata = by_method["Hierarchical: mean baseline"]["metadata"]
    lines += [
        "",
        "Effects and biases are in percentage points; the hierarchical row is an",
        "unweighted baseline conversion percentage, not a treatment effect. Its",
        "95% interval is a Bayesian credible interval; other rows use confidence intervals.",
        "",
        f"Hierarchical 94% partner-interval coverage: {metadata['calibration94']:.1%}. "
        f"Maximum R-hat: {metadata['max_rhat']:.3f}; "
        f"minimum bulk ESS: {metadata['min_bulk_ess']:.0f}; "
        f"divergences: {metadata['divergences']}.",
        "",
        f"Generated by `analysis/report.py` from a passing seed-0 run "
        f"({evidence['tests_collected']} tests collected).",
    ]
    return "\n".join(lines)


def write_report(results: Path, readme: Path) -> str:
    table = render(json.loads(results.read_text()))
    text = readme.read_text()
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        raise ValueError("README must contain one ordered methods marker pair")
    before = text.split(START)[0]
    after = text.split(END)[1]
    readme.write_text(before + START + "\n" + table + "\n" + END + after)
    return table


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=ROOT / "data/method-results.json")
    parser.add_argument("--readme", type=Path, default=ROOT / "README.md")
    args = parser.parse_args()
    print(write_report(args.results, args.readme))
